import {chromium,expect} from '@playwright/test';
import {writeFile} from 'node:fs/promises';
const base=process.env.RS_BASE||'http://localhost:4310';
const browser=await chromium.launch({channel:'chrome'});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
await context.addInitScript(()=>localStorage.setItem('rs.locale','en'));
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base+'/en',{waitUntil:'networkidle'});
await expect(page).toHaveTitle(/Bakalio/);
const tabs=page.getByRole('tablist').getByRole('tab');
await tabs.nth(0).focus();await page.keyboard.press('ArrowDown');await expect(tabs.nth(1)).toBeFocused();await expect(tabs.nth(1)).toHaveAttribute('aria-selected','true');
await expect(page.getByRole('tabpanel')).toContainText('Your writing. Your sources. Together.');
await tabs.nth(2).click();await expect(page.getByRole('tabpanel')).toContainText('Try a new direction');
await page.getByRole('link',{name:'Share feedback',exact:true}).click();await expect(page).toHaveURL(base+'/en/support');await expect(page.locator('textarea')).toBeVisible();
await page.goto(base+'/demo?view=overview');await expect(page.locator('.app-sidebar a.selected')).toHaveText('Overview');
await page.getByRole('link',{name:'Continue writing',exact:true}).first().click();await expect(page.locator('.tiptap')).toBeVisible();
await page.locator('.tiptap').fill('Keep this manuscript through a theme and language change.');
await page.getByLabel('Interface language').selectOption('zh');await expect(page.locator('.tiptap')).toContainText('Keep this manuscript');
await page.locator('.preferences button').click();await expect(page.locator('.tiptap')).toContainText('Keep this manuscript');
await page.setViewportSize({width:390,height:844});await expect(page.locator('.tiptap')).toBeVisible();
await page.goto(base+'/zh');await page.getByRole('button',{name:'导航',exact:true}).click();await expect(page.getByRole('link',{name:'产品功能',exact:true}).first()).toBeVisible();
expect(errors).toEqual([]);
await writeFile('../artifacts/bakalio-interactions.json',JSON.stringify({passed:true,checks:['brand title','keyboard scenario tabs','scenario content','feedback destination','demo selected navigation','editor persistence across language/theme','mobile menu'],pageErrors:errors},null,2));
console.log('Bakalio interaction checks passed');await browser.close();
